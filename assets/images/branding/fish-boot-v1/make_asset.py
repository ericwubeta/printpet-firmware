"""Encode the approved avatar for LVGL 9 without changing its character design.

This is runtime resampling/encoding only. Source image remains unmodified.
LVGL indexed palettes use byte order B,G,R,A (32-bit ARGB on little-endian CPUs).
"""
from pathlib import Path
import argparse
import hashlib
import json
import zlib

from PIL import Image
import PIL


APPROVED_SHA256 = '52095a6058dcd4947e8e22cf8bf9802e85919a815ef4a207e88100e7d30e2ca7'
SHA = lambda data: hashlib.sha256(data).hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def encode(source, output, size):
    raw_source = source.read_bytes()
    require(SHA(raw_source) == APPROVED_SHA256, 'Wrong approved source image')
    original = Image.open(source).convert('RGBA')
    output.mkdir(parents=True, exist_ok=True)
    padding = size // 16
    inner = size - 2 * padding
    # Pillow resizes RGBA via premultiplied RGBa internally to avoid dark fringes.
    reduced = original.resize((inner, inner), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    canvas.paste(reduced, (padding, padding))
    indexed = canvas.quantize(colors=256, method=Image.Quantize.FASTOCTREE,
                              dither=Image.Dither.NONE)
    palette_rgba = indexed.getpalette('RGBA')
    require(len(palette_rgba) == 1024, 'I8 needs a complete 256-entry palette')
    palette_bgra = bytes(channel for i in range(0, 1024, 4)
                         for channel in (palette_rgba[i+2], palette_rgba[i+1],
                                         palette_rgba[i], palette_rgba[i+3]))
    payload = palette_bgra + indexed.tobytes()
    require(len(payload) == 1024 + size * size, 'Unexpected I8 payload length')
    # Reconstruct from the encoded byte stream, not directly from the source PNG.
    rgba = bytes(channel for index in payload[1024:]
                 for channel in (payload[index*4+2], payload[index*4+1],
                                 payload[index*4], payload[index*4+3]))
    decoded = Image.frombytes('RGBA', (size, size), rgba)
    require(decoded.tobytes() == indexed.convert('RGBA').tobytes(),
            'Palette byte-order roundtrip failed')
    bbox = decoded.getbbox()
    require(bbox and bbox[0] >= padding and bbox[1] >= padding and
            bbox[2] <= size-padding and bbox[3] <= size-padding,
            'Character exceeds the transparent safety margin')
    alpha_min, alpha_max = decoded.getchannel('A').getextrema()
    require(alpha_min == 0 and alpha_max >= 250, 'Alpha was lost')
    canvas.save(output / 'resampled-rgba.png')
    indexed.save(output / 'indexed-source.png')
    decoded.save(output / 'decoded-preview.png')
    background = Image.new('RGBA', decoded.size, (4, 7, 10, 255))
    composited = Image.alpha_composite(background, decoded).convert('RGB')
    composited.save(output / 'on-boot-background.png')
    (output / 'fish_boot_payload.bin').write_bytes(payload)
    (output / 'fish_boot_img.h').write_text(
        '#pragma once\n#include "lvgl.h"\n\nextern const lv_image_dsc_t fish_boot_img;\n',
        encoding='utf-8')
    rows = [', '.join(f'0x{x:02x}' for x in payload[i:i+16]) + ','
            for i in range(0, len(payload), 16)]
    c = '''// Generated by make_asset.py from the user-approved fish avatar.
// Palette is B,G,R,A; bitmap is one index per pixel. No runtime allocation.
#include "fish_boot_img.h"

#if defined(__GNUC__)
#define FISH_BOOT_ALIGN __attribute__((aligned(4)))
#elif defined(_MSC_VER)
#define FISH_BOOT_ALIGN __declspec(align(4))
#else
#define FISH_BOOT_ALIGN
#endif

static FISH_BOOT_ALIGN const uint8_t fish_boot_pixels[] = {
'''+ '\n'.join(rows) + '''
};

const lv_image_dsc_t fish_boot_img = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_I8,
        .w = SIZE,
        .h = SIZE,
        .stride = SIZE,
    },
    .data_size = sizeof(fish_boot_pixels),
    .data = fish_boot_pixels,
};
'''
    (output / 'fish_boot_img.c').write_text(c.replace('SIZE', str(size)), encoding='utf-8')
    compressor = zlib.compressobj(level=9, wbits=11)
    compressed = compressor.compress(payload) + compressor.flush()
    manifest = {
        'asset': 'fish_boot_img', 'character': 'fish', 'characterName': '大肥鱼',
        'sourceFilename': source.name, 'sourceSha256': APPROVED_SHA256,
        'sourceSize': list(original.size), 'width': size, 'height': size,
        'format': 'LV_COLOR_FORMAT_I8', 'strideBytes': size,
        'paletteEntries': 256, 'paletteByteOrder': 'B,G,R,A',
        'paletteBytes': 1024, 'payloadBytes': len(payload),
        'payloadSha256': SHA(payload), 'payloadZlib11Bytes': len(compressed),
        'alphaRange': list(decoded.getchannel('A').getextrema()),
        'paletteAlphaLevels': len(set(palette_rgba[3::4])),
        'transparentPaddingPixels': padding, 'decodedBoundingBox': list(bbox),
        'resampling': 'Pillow RGBA LANCZOS (premultiplied-alpha resize)',
        'quantization': 'FASTOCTREE, 256 RGBA colors, no dithering',
        'pillowVersion': PIL.__version__, 'roundtripMatchesIndexedPng': True,
        'sourceUnchanged': SHA(source.read_bytes()) == APPROVED_SHA256,
        'frozenBaselineModified': False,
    }
    (output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path(__file__).parent)
    parser.add_argument('--size', type=int, choices=(96, 112, 128),
                        help='Encode only this size into --output; default retains the 128/112 pair')
    args = parser.parse_args()
    if args.size is not None:
        print(json.dumps(encode(args.source, args.output, args.size), ensure_ascii=False, indent=2))
        return
    primary = encode(args.source, args.output, 128)
    alternate = encode(args.source, args.output/'variants/112', 112)
    print(json.dumps({'primary': primary, 'alternate112': alternate}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
